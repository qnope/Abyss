#!/usr/bin/env python3
"""Writes the game's ARB translations as the .po files Godot loads.

    tool/arb_to_po.py            write godot/presentation/ui/l10n/{fr,en,es}.po
    tool/arb_to_po.py --check    fail if the committed .po differ from the ARB

The ARB files of lib/presentation/l10n stay the source until the switch to
Godot. Each entry of a .po is `msgid` = the ARB key and `msgstr` = the ICU
message verbatim: plurals and selects are not gettext's, so the game formats
them at run time (godot/presentation/ui/l10n/icu_format.gd).

Before writing, it checks that every language has the same keys, that every
message parses (icu_message.py), that a key has the same arguments in every
language, and that they are the ones its `@key` metadata declares. It exits
with 1, naming the key and the language, on the first problem.
"""

import argparse
import json
import os
import sys

import icu_message

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARB_DIR = os.path.join(REPO, "lib/presentation/l10n")
OUT_DIR = os.path.join(REPO, "godot/presentation/ui/l10n")
LANGUAGES = ("fr", "en", "es")

HEADER = """# Generated by tool/arb_to_po.py from lib/presentation/l10n/app_{language}.arb.
# Do not edit: change the ARB file and run the tool again.
msgid ""
msgstr ""
"Language: {language}\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"""


def escape(text):
    """[text] as the inside of a PO string."""
    for char, escaped in (("\\", "\\\\"), ('"', '\\"'), ("\n", "\\n"), ("\t", "\\t")):
        text = text.replace(char, escaped)
    return text


def load(arb_dir, languages):
    """{language: {key: message}} of the ARB files, validated.

    The keys come in the order of the first language's file.
    """
    messages, placeholders = {}, {}
    for language in languages:
        path = os.path.join(arb_dir, f"app_{language}.arb")
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        messages[language] = {k: v for k, v in data.items() if not k.startswith("@")}
        placeholders[language] = _parse_all(language, messages[language], data)
    _same_keys(messages, languages)
    template = languages[0]
    ordered = {}
    for language in languages:
        ordered[language] = {key: messages[language][key] for key in messages[template]}
    _same_arguments(placeholders, ordered[template], languages)
    return ordered


def _parse_all(language, messages, data):
    """{key: argument names}, failing on a message that does not parse."""
    found = {}
    for key, text in messages.items():
        try:
            names = icu_message.arguments(icu_message.parse(text))
        except icu_message.IcuError as error:
            raise ValueError(f"{language}: {key}: {error}") from error
        declared = data.get("@" + key, {}).get("placeholders")
        if declared is not None and set(declared) != names:
            raise ValueError(
                f"{language}: {key}: the placeholders {sorted(declared)} of the "
                f"metadata are not the arguments {sorted(names)} of the message")
        found[key] = names
    return found


def _same_keys(messages, languages):
    template = languages[0]
    for language in languages[1:]:
        missing = [k for k in messages[template] if k not in messages[language]]
        extra = [k for k in messages[language] if k not in messages[template]]
        if missing:
            raise ValueError(f"{language}: missing keys of {template}: {missing}")
        if extra:
            raise ValueError(f"{language}: keys {template} does not have: {extra}")


def _same_arguments(placeholders, template_messages, languages):
    template = languages[0]
    for key in template_messages:
        for language in languages[1:]:
            if placeholders[language][key] != placeholders[template][key]:
                raise ValueError(
                    f"{key}: arguments of {language} {sorted(placeholders[language][key])}"
                    f" differ from {template} {sorted(placeholders[template][key])}")


def render(language, messages):
    """The text of the .po file of [language]."""
    lines = [HEADER.format(language=language)]
    for key, text in messages.items():
        lines.append(f'msgid "{escape(key)}"\nmsgstr "{escape(text)}"\n')
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the .po are stale")
    parser.add_argument("--arb-dir", default=ARB_DIR)
    parser.add_argument("--out-dir", default=OUT_DIR)
    args = parser.parse_args(argv)
    try:
        messages = load(args.arb_dir, LANGUAGES)
    except ValueError as error:
        print(f"arb_to_po: {error}", file=sys.stderr)
        return 1
    stale = []
    for language in LANGUAGES:
        path = os.path.join(args.out_dir, f"{language}.po")
        text = render(language, messages[language])
        if args.check:
            if _read(path) != text:
                stale.append(path)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    for path in stale:
        print(f"arb_to_po: {path} is stale: run tool/arb_to_po.py", file=sys.stderr)
    return 1 if stale else 0


def _read(path):
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read()
    except FileNotFoundError:
        return None


if __name__ == "__main__":
    sys.exit(main())
