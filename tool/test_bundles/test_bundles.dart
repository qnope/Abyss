/// Gathers the test files into a few bundles, each one Dart entrypoint
/// running many test files in one process: `flutter test` compiles and
/// boots an engine per entrypoint, which costs more than most test files.
library;

import 'dart:io';
import 'dart:math';

/// The folder under `test/` the bundles are written in.
const bundlesFolder = 'bundles';

/// The test files under [testDir], as sorted paths relative to it, left
/// out the bundles; only those under the [only] paths (each
/// relative to the repository, as `test/domain`) when any is given.
List<String> findTestFiles(Directory testDir, {List<String> only = const []}) {
  final root = testDir.absolute.uri.path;
  final files = [
    for (final entity in testDir.listSync(recursive: true))
      if (entity is File && entity.path.endsWith('_test.dart'))
        entity.absolute.uri.path.substring(root.length),
  ].where((path) => path.split('/').first != bundlesFolder);
  final prefixes = only.map(_underTest).toList();
  return files
      .where((path) => prefixes.isEmpty || prefixes.any((p) => _isIn(path, p)))
      .toList()
    ..sort();
}

/// [path] relative to the test folder, with no slash at its ends.
String _underTest(String path) {
  final parts = path.split('/').where((part) => part.isNotEmpty).toList();
  return (parts.isNotEmpty && parts.first == 'test' ? parts.skip(1) : parts)
      .join('/');
}

bool _isIn(String path, String prefix) =>
    prefix.isEmpty || path == prefix || path.startsWith('$prefix/');

/// [files] mixed in an order set by [seed]; reversed for a negative one,
/// so a run in another order shows a test relying on the ones before it.
List<String> shuffleFiles(List<String> files, int seed) =>
    seed < 0 ? files.reversed.toList() : ([...files]..shuffle(Random(seed)));

/// [files] split into at most [count] bundles of about the same cost,
/// none empty: each file costs its entry in [costs], or [otherCost]; the
/// costliest
/// file goes first to the cheapest bundle. A bundle keeps its files in
/// their given order.
List<List<String>> splitIntoBundles(
  List<String> files,
  int count, {
  Map<String, double> costs = const {},
  double otherCost = 1,
}) {
  double cost(String file) => costs[file] ?? otherCost;
  final order = List.generate(files.length, (i) => i)..sort((a, b) {
    final byCost = cost(files[b]).compareTo(cost(files[a]));
    return byCost != 0 ? byCost : a.compareTo(b);
  });
  final bundles = List.generate(min(count, files.length), (_) => <int>[]);
  final loads = List.filled(bundles.length, 0.0);
  for (final index in order) {
    final cheapest = _indexOfMin(loads);
    bundles[cheapest].add(index);
    loads[cheapest] += cost(files[index]);
  }
  return [
    for (final bundle in bundles) [for (final i in bundle..sort()) files[i]],
  ];
}

int _indexOfMin(List<double> values) {
  var best = 0;
  for (var i = 1; i < values.length; i++) {
    if (values[i] < values[best]) best = i;
  }
  return best;
}

/// The source of a bundle running each of [files] (relative to `test/`)
/// in a group named by its path, after putting the process back as at
/// startup; it lives in `test/bundles/`.
String renderBundle(List<String> files) {
  final out =
      StringBuffer()
        ..writeln('// GENERATED by tool/test_bundles.dart: do not edit.')
        ..writeln("import 'package:flutter_test/flutter_test.dart';")
        ..writeln()
        ..writeln("import '../helpers/fresh_process.dart';");
  for (var i = 0; i < files.length; i++) {
    out.writeln("import '../${files[i]}' as t$i;");
  }
  out
    ..writeln()
    ..writeln('void main() {');
  for (var i = 0; i < files.length; i++) {
    out
      ..writeln("  group('${_quoted(files[i])}', () {")
      ..writeln('    setUpAll(resetProcessState);')
      ..writeln('    t$i.main();')
      ..writeln('  });');
  }
  return (out..writeln('}')).toString();
}

String _quoted(String text) =>
    text.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');
